#!/usr/bin/env python3
"""Turn every verified/*.json into a Flyway migration. Usage: build_migration.py <out.sql>"""
import glob, json, os, sys, uuid

HERE = os.path.dirname(os.path.abspath(__file__))
NS = uuid.UUID("b17eba77-1e00-4c0d-9e8f-000000000031")
def uid(*parts): return str(uuid.uuid5(NS, ":".join(parts)))
def dq(tag, s):
    assert f"${tag}$" not in s, "dollar-quote collision"
    return f"${tag}${s}${tag}$"
def sql_str(s): return "'" + s.replace("'", "''") + "'"

MAX_INPUT = 30000   # bytes of stdin per test: keeps the database small and every submission quick on Judge0
dropped = []

def keep_tests(tests, label, minimum=5):
    kept = [t for t in tests if len(t["input"]) <= MAX_INPUT]
    for t in tests:
        if len(t["input"]) > MAX_INPUT: dropped.append((label, len(t["input"])))
    assert len(kept) >= minimum and sum(1 for t in kept if not t.get("hidden")) >= 2, f"{label}: too few tests left after size cap"
    return kept

def main(out):
    battles, questions, coding, debug = [], [], [], []
    files = sorted(glob.glob(os.path.join(HERE, "verified", "*.json")))
    for f in files:
        d = json.load(open(f)); cid = d["conceptId"]; b = d.get("battle"); bid = uid(cid, "battle")
        qs = b["questions"] if b else []
        if b: battles.append(f"    ({sql_str(bid)}, {sql_str(cid)}, {sql_str(b['title'])}, {sql_str(b['description'])}, {sql_str(b['battleType'])}, {sql_str(b['difficulty'])}, {len(qs)}, {int(b.get('timeLimitSeconds', 300))}, 3, 'ACTIVE', now(), now())")
        for n, q in enumerate(qs, 1):
            text = q["text"]
            if q["type"] == "PREDICT_OUTPUT" and q.get("code"):
                text = 'What does this program print? (Lines are shown separated by " / ".)\n\n' + q["code"].rstrip() + "\n"
            questions.append(f"    ({sql_str(uid(cid, 'q', str(n)))}, {sql_str(bid)}, {dq('q', text)}, {sql_str(q['type'])}, {dq('o', json.dumps(q['options']))}, {dq('a', q['answer'])}, {dq('e', q['explanation'])}, {q['points']}, {n}, now(), now())")
        for n, c in enumerate(d.get("coding", []), 1):
            tests = [{"input": t["input"], "expectedOutput": t["expectedOutput"], "hidden": bool(t.get("hidden"))} for t in keep_tests(c["tests"], cid[-4:] + " " + c["title"])]
            coding.append(f"    ({sql_str(uid(cid, 'code', str(n)))}, {sql_str(cid)}, {sql_str(c['title'])}, {dq('d', c['description'])}, {sql_str(c['difficulty'])}, 'JAVA', {dq('i', c['inputDescription'])}, {dq('p', c['outputDescription'])}, {dq('k', c['constraints'])},\n     {dq('s', c['starterCode'])},\n     {dq('c', c['solutionCode'])},\n     {dq('t', json.dumps(tests, indent=1))},\n     5000, 256, now(), now())")
        for n, x in enumerate(d.get("debug", []), 1):
            tests = [{"input": t["input"], "expectedOutput": t["expectedOutput"], "hidden": bool(t.get("hidden"))} for t in keep_tests(x["tests"], cid[-4:] + " " + x["title"], 4)]
            debug.append(f"    ({sql_str(uid(cid, 'debug', str(n)))}, {sql_str(cid)}, {sql_str(x['title'])}, {dq('d', x['description'])},\n     {dq('b', x['buggyCode'])},\n     'JAVA',\n     {dq('t', json.dumps(tests, indent=1))},\n     {dq('h', json.dumps(x['hints'], indent=1))},\n     {sql_str(x['bugCategory'])}, {sql_str(x['difficulty'])},\n     {dq('s', x['solutionCode'])}, now())")
    with open(out, "w") as o:
        o.write(f"-- Battles, coding challenges and debugging exercises for the rest of the curriculum ({len(files)} concepts).\n")
        o.write("-- Generated by content-authoring/build_migration.py. Every PREDICT_OUTPUT program, reference solution and buggy\n")
        o.write("-- program was executed on Judge0: expected outputs come from the solutions, and each starter / buggy version was\n-- confirmed to fail at least one test. Idempotent via deterministic ids and ON CONFLICT DO NOTHING.\n\n")
        if battles:
            o.write("INSERT INTO battles (id, concept_id, title, description, battle_type, difficulty, total_questions, time_limit_seconds, total_lives, status, created_at, updated_at) VALUES\n" + ",\n".join(battles) + "\nON CONFLICT DO NOTHING;\n\n")
            o.write("INSERT INTO battle_questions (id, battle_id, question_text, question_type, options, correct_answer, explanation, points, display_order, created_at, updated_at) VALUES\n" + ",\n".join(questions) + "\nON CONFLICT DO NOTHING;\n\n")
        if coding:
            o.write("INSERT INTO coding_challenges (id, concept_id, title, description, difficulty, language, input_description, output_description, constraints, starter_code, solution_code, test_cases, time_limit_ms, memory_limit_mb, created_at, updated_at) VALUES\n" + ",\n".join(coding) + "\nON CONFLICT DO NOTHING;\n\n")
        if debug:
            o.write("INSERT INTO debug_exercises (id, concept_id, title, description, buggy_code, language, test_cases_json, hint_ladder_json, bug_category, difficulty, solution_code, created_at) VALUES\n" + ",\n".join(debug) + "\nON CONFLICT DO NOTHING;\n")
    for label, n in dropped: print(f"  dropped oversize test ({n} bytes): {label}")
    print(f"wrote {out}: {len(battles)} battles, {len(questions)} questions, {len(coding)} coding, {len(debug)} debug")

if __name__ == "__main__":
    main(sys.argv[1])
